// Builds src/lib/dictionary.ts: real English words that are one or two letters away
// from a word the help center uses. The spelling fixer leaves these alone, so
// "boots" isn't "fixed" to "book" while "shiping" still becomes "shipping".
// Source: /usr/share/dict/words (Webster's Second International, public domain).
// Run: node --experimental-strip-types scripts/make-dictionary.ts
import { readFileSync, writeFileSync } from "node:fs";
import { stem, words } from "../src/lib/engine.ts";
import { ARTICLES, SYNONYMS } from "../src/lib/kb.ts";

const vocab = new Set<string>();
for (const a of ARTICLES) for (const w of words(`${a.title} ${a.body}`)) vocab.add(stem(w));
for (const g of SYNONYMS) for (const t of g.terms) for (const w of words(t)) vocab.add(stem(w));
// Common words people use in support chats that the 1934 dictionary lacks or spells differently.
const extra = "email emails online website app login password paypal zipper zippers laptop phone phones okay ok weekend tons kinda stuff".split(" ");

function near(a: string, b: string, max: number): boolean {
  if (Math.abs(a.length - b.length) > max) return false;
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) cur.push(Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)));
    if (Math.min(...cur) > max) return false;
    prev = cur;
  }
  return prev[b.length] <= max;
}

const byFirst = new Map<string, string[]>();
for (const v of vocab) if (v.length >= 3) byFirst.set(v[0], [...(byFirst.get(v[0]) ?? []), v]);
const out = new Set<string>();
for (const raw of [...readFileSync("/usr/share/dict/words", "utf8").split("\n"), ...extra]) {
  const w = raw.trim().toLowerCase();
  if (w.length < 4 || w.length > 14 || !/^[a-z]+$/.test(w)) continue;
  const s = stem(w);
  if (vocab.has(s)) continue;
  if ((byFirst.get(s[0]) ?? []).some((v) => near(s, v, s.length >= 9 ? 2 : 1))) out.add(w);
}
const list = [...out].sort();
writeFileSync(
  new URL("../src/lib/dictionary.ts", import.meta.url),
  `// Generated by scripts/make-dictionary.ts. Real English words close to help center words; see that script.\nexport const REAL_WORDS = new Set(\n  "${list.join(" ")}".split(" "),\n);\n`,
);
console.log(`${list.length} words`);
